#!/usr/bin/env node

import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { spawnSync } from "node:child_process";
import { join, resolve } from "node:path";
import { tmpdir } from "node:os";
import { profilesForServerIdentity } from "./profile-canonical-contract.mjs";
import { securityRegistrySetHash } from "./security-registry-set-contract.mjs";
import { loadRealFixture, readRealFixtureManifest } from "./tlsn-benchmark-fixtures.mjs";

const packageDirectory = resolve(new URL("..", import.meta.url).pathname);
const provisionerPath = resolve(packageDirectory, "scripts/provision-canary-material.mjs");

function parseGeneratedEnv(raw) {
  return Object.fromEntries(
    raw
      .split(/\r?\n/)
      .filter((line) => line.trim())
      .map((line) => {
        const separator = line.indexOf("=");
        assert.ok(separator > 0, `invalid generated env line: ${line}`);
        return [line.slice(0, separator), JSON.parse(line.slice(separator + 1))];
      }),
  );
}

function runProvisioner(outputDirectory, argumentsList) {
  const result = spawnSync(process.execPath, [provisionerPath, "--output", outputDirectory, ...argumentsList], {
    cwd: packageDirectory,
    encoding: "utf8",
    env: {
      PATH: process.env.PATH ?? "/usr/bin:/bin",
      HOME: process.env.HOME ?? tmpdir(),
    },
  });
  assert.equal(result.status, 0, `${result.stdout}\n${result.stderr}`);
}

function expectedGeneratedCanaryKeyId(deploymentId, purpose, publicKeySpki) {
  const deploymentPart = deploymentId.length <= 80
    ? deploymentId
    : createHash("sha256").update(deploymentId, "utf8").digest("base64url").slice(0, 24);
  const materialFingerprint = createHash("sha256")
    .update(Buffer.from(publicKeySpki, "base64url"))
    .digest("base64url")
    .slice(0, 16);
  return `canary-${deploymentPart}-${purpose}-${materialFingerprint}`;
}

async function readProvisioned(outputDirectory) {
  return {
    manifest: JSON.parse(await readFile(join(outputDirectory, "manifest.json"), "utf8")),
    generatedEnv: parseGeneratedEnv(await readFile(join(outputDirectory, "canary.env"), "utf8")),
  };
}

const rootDirectory = await mkdtemp(join(tmpdir(), "tlsn-production-canary-provisioning-test-"));
try {
  const incompleteDirectory = join(rootDirectory, "incomplete");
  runProvisioner(incompleteDirectory, ["--fixture-only", "false"]);
  const incomplete = await readProvisioned(incompleteDirectory);
  assert.equal(incomplete.manifest.mode, "supplied");
  assert.equal(incomplete.manifest.status, "incomplete");
  for (const name of [
    "TLSN_CANARY_DEPLOYMENT_ID",
    "TLSN_CANARY_WORKER_NAME",
    "TLSN_PRODUCTION_NOTARY_REGISTRY",
    "TLSN_CANDIDATE_SERVER_IDENTITY",
    "TLSN_CANDIDATE_PROFILE_SHA256",
    "TLSN_CANDIDATE_SPARSE_PROFILE_SHA256",
    "TLSN_CANARY_TRUST_ROOT_CERTIFICATE_DER",
  ]) {
    assert.ok(incomplete.manifest.unresolved_inputs.includes(name), `${name} must remain unresolved`);
    assert.equal(Object.hasOwn(incomplete.generatedEnv, name), false, `${name} must not be autogenerated`);
  }
  assert.equal(incomplete.manifest.generated_public_identity.deployment_id, null);
  assert.equal(incomplete.manifest.generated_public_identity.worker_name, null);
  assert.equal(incomplete.manifest.notary.registry_sha256, null);
  assert.equal(incomplete.manifest.notary.source, "unresolved_explicit_input");
  assert.equal(await readFile(join(incompleteDirectory, "notary-signing-key.base64url")).catch(() => null), null);

  const { entries } = readRealFixtureManifest();
  const fixture = loadRealFixture(entries.get("p50"));
  const profiles = profilesForServerIdentity("canary.example.net");
  const profileDirectory = join(rootDirectory, "inputs");
  await mkdir(profileDirectory, { recursive: true });
  await writeFile(join(profileDirectory, "complete.json"), `${profiles.complete.canonical}\n`);
  await writeFile(join(profileDirectory, "sparse.json"), `${profiles.sparse.canonical}\n`);
  await writeFile(join(profileDirectory, "trust-root.der"), Buffer.from(fixture.root_certificate_base64, "base64url"));
  await writeFile(join(profileDirectory, "notary-registry.json"), `${JSON.stringify({ "notary-production-2026": fixture.notary_key_base64 })}\n`);

  const completeDirectory = join(rootDirectory, "complete");
  const explicitArguments = [
    "--fixture-only", "false",
    "--server-identity", "canary.example.net",
    "--profile-file", join(profileDirectory, "complete.json"),
    "--sparse-profile-file", join(profileDirectory, "sparse.json"),
    "--trust-root-file", join(profileDirectory, "trust-root.der"),
    "--notary-registry-file", join(profileDirectory, "notary-registry.json"),
    "--notary-key-id", "notary-production-2026",
    "--verifier-key-id", "verifier-production-2026",
    "--deployment-id", "canary-explicit-2026",
    "--worker-name", "fusou-tlsn-verification-canary-2026",
  ];
  runProvisioner(completeDirectory, explicitArguments);
  const complete = await readProvisioned(completeDirectory);
  assert.equal(complete.generatedEnv.TLSN_CANARY_FIXTURE_ONLY, "false");
  assert.equal(complete.generatedEnv.TLSN_CANDIDATE_SERVER_IDENTITY, "canary.example.net");
  assert.equal(complete.generatedEnv.TLSN_CANDIDATE_PROFILE_SHA256, profiles.complete.sha256);
  assert.equal(complete.generatedEnv.TLSN_CANDIDATE_SPARSE_PROFILE_SHA256, profiles.sparse.sha256);
  assert.equal(complete.generatedEnv.TLSN_CANDIDATE_NOTARY_KEY_ID, "notary-production-2026");
  assert.deepEqual(JSON.parse(complete.generatedEnv.TLSN_PRODUCTION_NOTARY_REGISTRY), {
    "notary-production-2026": fixture.notary_key_base64,
  });
  assert.equal(complete.generatedEnv.TLSN_CANARY_DEPLOYMENT_ID, "canary-explicit-2026");
  assert.equal(complete.generatedEnv.TLSN_CANARY_WORKER_NAME, "fusou-tlsn-verification-canary-2026");
  const expectedSecurityRegistrySet = securityRegistrySetHash({
    notaryKeyId: "notary-production-2026",
    notaryRegistryRaw: complete.generatedEnv.TLSN_PRODUCTION_NOTARY_REGISTRY,
    profileSha256: profiles.complete.sha256,
    serverIdentity: "canary.example.net",
    sparseProfileSha256: profiles.sparse.sha256,
  });
  assert.equal(complete.generatedEnv.TLSN_SECURITY_REGISTRY_SET_SHA256, expectedSecurityRegistrySet.sha256);
  assert.equal(complete.manifest.security_registry_set_sha256, expectedSecurityRegistrySet.sha256);
  assert.equal(complete.manifest.security_registry_set_source, "derived-from-explicit-inputs");
  const mutationNotaryRegistry = JSON.stringify({
    "notary-production-2026": fixture.notary_key_base64,
    "notary-production-2027": fixture.notary_key_base64,
  });
  for (const [label, inputs] of [
    ["Notary registry", { notaryRegistryRaw: mutationNotaryRegistry }],
    ["Notary key ID", { notaryKeyId: "notary-production-2027", notaryRegistryRaw: mutationNotaryRegistry }],
    ["complete profile", { profileSha256: Buffer.alloc(32, 1).toString("base64url") }],
    ["server identity", { serverIdentity: "other.example.net" }],
    ["sparse profile", { sparseProfileSha256: Buffer.alloc(32, 2).toString("base64url") }],
  ]) {
    assert.notEqual(
      securityRegistrySetHash({
        notaryKeyId: inputs.notaryKeyId ?? "notary-production-2026",
        notaryRegistryRaw: inputs.notaryRegistryRaw ?? complete.generatedEnv.TLSN_PRODUCTION_NOTARY_REGISTRY,
        profileSha256: inputs.profileSha256 ?? profiles.complete.sha256,
        serverIdentity: inputs.serverIdentity ?? "canary.example.net",
        sparseProfileSha256: inputs.sparseProfileSha256 ?? profiles.sparse.sha256,
      }).sha256,
      expectedSecurityRegistrySet.sha256,
      `${label} mutation must change the security registry set hash`,
    );
  }
  assert.equal(complete.manifest.notary.source, "explicit_input_file");
  assert.equal(complete.manifest.generated_public_identity.deployment_id, "canary-explicit-2026");
  assert.equal(complete.manifest.generated_public_identity.worker_name, "fusou-tlsn-verification-canary-2026");
  assert.equal(
    complete.manifest.generated_public_identity.key_id_strategy,
    "deployment-id-plus-public-key-sha256-prefix",
  );
  const generatedKeyIdNames = [
    ["TLSN_CANARY_RESULT_SIGNER_KEY_ID", "result", "TLSN_CANARY_RESULT_PUBLIC_KEY_SPKI"],
    ["TLSN_CANARY_RESULT_REGISTRY_ROOT_KEY_ID", "result-root", "TLSN_CANARY_RESULT_REGISTRY_ROOT_PUBLIC_KEY_SPKI"],
    ["TLSN_CANARY_SESSION_AUTHORITY_KEY_ID", "session", "TLSN_CANARY_SESSION_AUTHORITY_PUBLIC_KEY_SPKI"],
    ["TLSN_CANARY_BINDING_AUTHORITY_KEY_ID", "binding", "TLSN_CANARY_BINDING_AUTHORITY_PUBLIC_KEY_SPKI"],
  ];
  for (const [name, purpose, publicKeyName] of generatedKeyIdNames) {
    const expectedKeyId = expectedGeneratedCanaryKeyId(
      complete.generatedEnv.TLSN_CANARY_DEPLOYMENT_ID,
      purpose,
      complete.generatedEnv[publicKeyName],
    );
    assert.equal(complete.generatedEnv[name], expectedKeyId, `${name} must follow the deterministic generated ID contract`);
    const mutatedPublicKey = `${complete.generatedEnv[publicKeyName].slice(0, -1)}${complete.generatedEnv[publicKeyName].endsWith("A") ? "B" : "A"}`;
    assert.notEqual(
      expectedGeneratedCanaryKeyId(complete.generatedEnv.TLSN_CANARY_DEPLOYMENT_ID, purpose, mutatedPublicKey),
      complete.generatedEnv[name],
      `${name} must bind the public-key fingerprint into the ID`,
    );
  }
  const repeatedDirectory = join(rootDirectory, "repeated");
  runProvisioner(repeatedDirectory, explicitArguments);
  const repeated = await readProvisioned(repeatedDirectory);
  for (const [name] of generatedKeyIdNames) {
    assert.notEqual(
      complete.generatedEnv[name],
      repeated.generatedEnv[name],
      `${name} must not be reused across reprovisioning with fresh key material`,
    );
  }
  for (const name of [
    "TLSN_CANARY_WORKER_NAME",
    "TLSN_PRODUCTION_NOTARY_REGISTRY",
    "TLSN_CANDIDATE_SERVER_IDENTITY",
    "TLSN_CANDIDATE_PROFILE_SHA256",
    "TLSN_CANDIDATE_SPARSE_PROFILE_SHA256",
    "TLSN_CANARY_TRUST_ROOT_CERTIFICATE_DER",
  ]) {
    assert.equal(complete.manifest.unresolved_inputs.includes(name), false, `${name} must be resolved`);
  }
  assert.equal(await readFile(join(completeDirectory, "notary-signing-key.base64url")).catch(() => null), null);
} finally {
  await rm(rootDirectory, { recursive: true, force: true });
}

console.log("[tlsn-production-canary-provisioning] explicit-input and unresolved-input contract PASS");
