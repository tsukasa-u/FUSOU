import { ReleaseBlocked } from "./release-transport.mjs";

export const NATIVE_ROOT = "packages/FUSOU-TLSN-VERIFIER";
export const NATIVE_BINARY = "verify_fusou_tlsn_evidence";
export const NATIVE_WORKFLOW = ".github/workflows/tlsn-native-build.yml";
export const NATIVE_POLICY = "scripts/release-native-policy.draft.json";
export const NATIVE_ATTEST_ACTION = "actions/attest@1e69f48acb82d1966a394da916b4c1698aa569d6";
export const NATIVE_BLOCKER = "FORMAL_NATIVE_BUILD_IDENTITY_CONTRACT_UNDEFINED";
export const NATIVE_INPUT_PATHS = Object.freeze([
  `${NATIVE_ROOT}/Cargo.toml`, `${NATIVE_ROOT}/Cargo.lock`,
  `${NATIVE_ROOT}/src/bin/${NATIVE_BINARY}.rs`, NATIVE_WORKFLOW,
]);
const recipeKeys = ["toolchain", "target", "profile", "features", "default_features"];
const sha = (value) => typeof value === "string" && /^[0-9a-f]{40}$/.test(value);
const digest = (value) => typeof value === "string" && /^[A-Za-z0-9_-]{43}$/.test(value);
const id = (value) => typeof value === "string" && /^[1-9][0-9]*$/.test(value);
const positive = (value) => Number.isSafeInteger(value) && value > 0;
const hex = (raw) => createHash("sha256").update(raw).digest("hex");
const exact = (object, keys) => object !== null && typeof object === "object" && !Array.isArray(object) &&
  isDeepStrictEqual(Object.keys(object).sort(), [...keys].sort());
const descriptor = (raw) => ({ sha256: sha256(raw), byte_length: raw.byteLength });
const bytes = (raw) => raw instanceof Uint8Array && raw.byteLength > 0;
const section = (text, name) => text.split(`[${name}]`)[1]?.split(/\r?\n\s*\[/)[0] ?? "";
const contextKeys = ["repository", "repository_id", "repository_owner_id", "source_sha",
  "workflow_path", "workflow_sha", "run_id", "run_attempt"];
function assertNativeContext(context) {
  requireRelease(exact(context, contextKeys) && context.repository === "tsukasa-u/FUSOU" &&
    id(context.repository_id) && id(context.repository_owner_id) && sha(context.source_sha) &&
    sha(context.workflow_sha) && context.workflow_path === NATIVE_WORKFLOW &&
    positive(context.run_id) && positive(context.run_attempt), "native independent repository/build context");
}

export function nativeBuildRecipe(recipe) {
  requireRelease(exact(recipe, recipeKeys) && /^\d+\.\d+\.\d+$/.test(recipe.toolchain) &&
    recipe.target === "x86_64-unknown-linux-gnu" && recipe.profile === "release" &&
    Array.isArray(recipe.features) && recipe.features.length === 0 && recipe.default_features === true,
  "native candidate toolchain/target/features/flags");
  return {
    workspace_root: NATIVE_ROOT, package: "fusou-tlsn-verifier", binary: NATIVE_BINARY,
    ...structuredClone(recipe),
    argv: [`+${recipe.toolchain}`, "build", "--locked", "--release", "--manifest-path", `${NATIVE_ROOT}/Cargo.toml`,
      "--bin", NATIVE_BINARY, "--target", recipe.target],
    environment: { CARGO_TARGET_DIR: `${NATIVE_ROOT}/target`, RUSTFLAGS: "", CARGO_ENCODED_RUSTFLAGS: "", RUSTDOCFLAGS: "" },
    output: `${NATIVE_ROOT}/target/${recipe.target}/release/${NATIVE_BINARY}`,
  };
}

export function inspectNativeBuildInputs({ files, trackedPaths }) {
  const errors = [];
  requireRelease(files instanceof Map && Array.isArray(trackedPaths), "native source snapshot");
  for (const path of NATIVE_INPUT_PATHS) {
    if (!bytes(files.get(path))) errors.push({ path, code: "NATIVE_INPUT_MISSING" });
    if (!trackedPaths.includes(path)) errors.push({ path, code: "NATIVE_INPUT_UNTRACKED" });
  }
  const manifest = Buffer.from(files.get(NATIVE_INPUT_PATHS[0]) ?? []).toString("utf8");
  const lock = Buffer.from(files.get(NATIVE_INPUT_PATHS[1]) ?? []).toString("utf8");
  const pkg = section(manifest, "package");
  if (!/^name\s*=\s*"fusou-tlsn-verifier"\s*$/m.test(pkg) ||
    !/^\[workspace\]\s*$/m.test(manifest) ||
    !manifest.split("[[bin]]").slice(1).some((block) =>
      /^name\s*=\s*"verify_fusou_tlsn_evidence"\s*$/m.test(block.split(/\r?\n\s*\[/)[0]) &&
      /^path\s*=\s*"src\/bin\/verify_fusou_tlsn_evidence\.rs"\s*$/m.test(block.split(/\r?\n\s*\[/)[0]))) {
    errors.push({ path: NATIVE_INPUT_PATHS[0], code: "NATIVE_WORKSPACE_OR_TARGET_UNRESOLVED" });
  }
  const version = pkg.match(/^version\s*=\s*"([^"]+)"\s*$/m)?.[1];
  if (!/^# This file is automatically @generated by Cargo\./.test(lock) || !/^version = 4\s*$/m.test(lock) ||
    !version || !lock.split("[[package]]").some((block) =>
      /^name = "fusou-tlsn-verifier"\s*$/m.test(block) &&
      block.match(/^version = "([^"]+)"\s*$/m)?.[1] === version)) {
    errors.push({ path: NATIVE_INPUT_PATHS[1], code: "NATIVE_LOCKFILE_SCOPE_UNRESOLVED" });
  }
  return { errors, inputs: Object.fromEntries(NATIVE_INPUT_PATHS.filter((path) => bytes(files.get(path)))
    .map((path) => [path, descriptor(files.get(path))])), cargo_locked_consistency: "NOT_CHECKED",
  complete_dependency_closure: "NOT_CHECKED" };
}

export function nativeBuildPreflight({ files, trackedPaths, policy }) {
  const source = inspectNativeBuildInputs({ files, trackedPaths }), blockers = source.errors.map((error) => error.code);
  if (!policy || policy.schema_version !== 1 || policy.scope !== "fusou-native-build-candidate-v1" ||
    policy.lifecycle !== "PROPOSED" || policy.operational_enabled !== false || policy.publication_authorized !== false ||
    policy.repository !== "tsukasa-u/FUSOU" || policy.workflow_path !== NATIVE_WORKFLOW) blockers.push("NATIVE_CANDIDATE_POLICY_INVALID");
  if (!id(policy?.repository_id) || !id(policy?.repository_owner_id)) blockers.push("NATIVE_REPOSITORY_IDENTITY_NOT_REGISTERED");
  if (!sha(policy?.trusted_workflow_sha)) blockers.push("NATIVE_SIGNER_WORKFLOW_PIN_MISSING");
  if (policy?.recipe_approval !== "APPROVED") blockers.push("NATIVE_BUILD_PINS_UNAPPROVED");
  let recipe;
  try { recipe = nativeBuildRecipe(policy?.recipe); }
  catch (error) {
    if (!(error instanceof Error) || !error.message.startsWith("release consumer: native candidate")) throw error;
    blockers.push("NATIVE_BUILD_RECIPE_INVALID");
  }
  if (policy?.attestation_action !== NATIVE_ATTEST_ACTION || policy?.attestation_action_contract !== "VERIFIED") {
    blockers.push("NATIVE_ATTEST_ACTION_CONTRACT_NOT_VERIFIED");
  }
  if (policy?.repository_attestation_eligibility !== "VERIFIED") blockers.push("NATIVE_ATTESTATION_ELIGIBILITY_NOT_VERIFIED");
  // There is no registered real verifier or launcher, regardless of record labels.
  blockers.push("NATIVE_ATTESTATION_VERIFIER_NOT_REGISTERED", "NATIVE_ARTIFACT_ACQUISITION_NOT_REGISTERED",
    "NATIVE_LAUNCHER_NOT_IMPLEMENTED", NATIVE_BLOCKER);
  return { schema_version: 1, scope: "fusou-native-build-preflight-v1", status: "BLOCKED_IMPLEMENTATION",
    source_contract: source.errors.length ? "BLOCKED_IMPLEMENTATION" : "SOURCE_CONTRACT_READY",
    ...source, recipe, blockers: [...new Set(blockers)], build_authorized: false, authenticated: false,
    offline_verification: NATIVE_BLOCKER, publication_authorized: false,
    deployment: "NOT_CHECKED", production_acceptance: "BLOCKED" };
}

export async function readNativeBuildPreflight() {
  const root = new URL("../", import.meta.url), paths = [...NATIVE_INPUT_PATHS, NATIVE_POLICY];
  const trackedPaths = execFileSync("git", ["-c", "core.fsmonitor=false", "ls-files", "--", ...paths],
    { cwd: fileURLToPath(root), encoding: "utf8" }).trim().split("\n").filter(Boolean);
  const files = new Map();
  for (const path of paths) {
    try { files.set(path, await readRegularFile(new URL(path, root))); }
    catch (error) { if (error.code !== "ENOENT") throw error; }
  }
  const policyRaw = files.get(NATIVE_POLICY);
  const policy = policyRaw ? JSON.parse(new TextDecoder("utf-8", { fatal: true }).decode(policyRaw)) : undefined;
  return nativeBuildPreflight({ files, trackedPaths, policy });
}

export function createNativeBuildMetadata({ files, trackedPaths, recipe, context, compilerIdentity, binary }) {
  const source = inspectNativeBuildInputs({ files, trackedPaths });
  requireRelease(source.errors.length === 0, "native tracked build input contract");
  assertNativeContext(context);
  requireRelease(bytes(binary) &&
    typeof compilerIdentity === "string" && compilerIdentity.trim().length > 0, "native candidate build context/output");
  const buildRecipe = nativeBuildRecipe(recipe);
  return { schema_version: 1, scope: "fusou-native-build-metadata-candidate-v1",
    context: structuredClone(context), inputs: source.inputs, recipe: buildRecipe,
    recipe_sha256: sha256(Buffer.from(canonicalJson(buildRecipe))), compiler_identity: compilerIdentity,
    artifact: { path: buildRecipe.output, sha256: hex(binary), byte_length: binary.byteLength },
    authentication: "UNVERIFIED" };
}

function assertNativeExpectations(expected) {
  if (!sha(expected?.context?.workflow_sha)) throw new ReleaseBlocked("NATIVE_SIGNER_WORKFLOW_PIN_MISSING", "BLOCKED_IMPLEMENTATION");
  requireRelease(exact(expected, ["context", "inputs", "recipe", "compiler_identity", "artifact_origin"]) &&
    exact(expected.inputs, NATIVE_INPUT_PATHS) && Object.values(expected.inputs).every((input) =>
      exact(input, ["sha256", "byte_length"]) && digest(input.sha256) && positive(input.byte_length)) &&
    typeof expected.compiler_identity === "string" && expected.compiler_identity.trim().length > 0,
  "native independent repository/build expectations");
  assertNativeContext(expected.context);
  const origin = expected.artifact_origin;
  requireRelease(exact(origin, ["id", "name", "digest", "run_id", "run_attempt", "workflow_sha", "repository_id"]) &&
    positive(origin.id) && origin.name === `fusou-native-${expected.context.run_id}-${expected.context.run_attempt}` &&
    /^sha256:[0-9a-f]{64}$/.test(origin.digest) && origin.run_id === expected.context.run_id &&
    origin.run_attempt === expected.context.run_attempt && origin.workflow_sha === expected.context.workflow_sha &&
    origin.repository_id === expected.context.repository_id, "native independent artifact origin");
  nativeBuildRecipe(expected.recipe);
}

export async function inspectNativeArtifactCandidate({ binary, metadataBytes, expected, provenance, artifactOrigin }, { mockVerifier } = {}) {
  assertNativeExpectations(expected);
  requireRelease(isDeepStrictEqual(artifactOrigin, expected.artifact_origin), "native candidate artifact origin mismatch");
  requireRelease(bytes(binary), "native raw executable required");
  const metadata = parseReleaseRecord(metadataBytes), recipe = nativeBuildRecipe(expected.recipe);
  requireRelease(exact(metadata, ["schema_version", "scope", "context", "inputs", "recipe", "recipe_sha256",
    "compiler_identity", "artifact", "authentication"]) &&
    metadata.schema_version === 1 && metadata.scope === "fusou-native-build-metadata-candidate-v1" &&
    metadata.authentication === "UNVERIFIED" && isDeepStrictEqual(metadata.context, expected.context) &&
    isDeepStrictEqual(metadata.inputs, expected.inputs) && isDeepStrictEqual(metadata.recipe, recipe) &&
    metadata.recipe_sha256 === sha256(Buffer.from(canonicalJson(recipe))) &&
    metadata.compiler_identity === expected.compiler_identity &&
    isDeepStrictEqual(metadata.artifact, { path: recipe.output, sha256: hex(binary), byte_length: binary.byteLength }),
  "native candidate binary/metadata/independent identity mismatch");
  if (!bytes(provenance)) throw new ReleaseBlocked("NATIVE_ATTESTATION_MISSING", "BLOCKED_IMPLEMENTATION");
  if (typeof mockVerifier !== "function") throw new ReleaseBlocked("NATIVE_ATTESTATION_VERIFIER_NOT_REGISTERED", "BLOCKED_IMPLEMENTATION");
  const snapshot = { binary: hex(binary), metadata: hex(metadataBytes), provenance: hex(provenance),
    expected: canonicalJson(expected), origin: canonicalJson(artifactOrigin) };
  const statement = { predicate_type: "https://slsa.dev/provenance/v1", ...structuredClone(expected.context),
    subjects: { executable_sha256: snapshot.binary, metadata_sha256: snapshot.metadata } };
  const result = await mockVerifier({ provenance: Buffer.from(provenance), expected: structuredClone(statement) });
  requireRelease(hex(binary) === snapshot.binary && hex(metadataBytes) === snapshot.metadata &&
    hex(provenance) === snapshot.provenance && canonicalJson(expected) === snapshot.expected &&
    canonicalJson(artifactOrigin) === snapshot.origin,
  "native candidate inputs changed during mock verification");
  requireRelease(isDeepStrictEqual(result, statement), "native mock attestation predicate/subjects/signer/source/run mismatch");
  return { status: "BLOCKED_IMPLEMENTATION", candidate_consistency: "VERIFIED", verification_mode: "MOCK_ONLY",
    signature_verification: "UNVERIFIED", signer_authentication: "UNVERIFIED", authenticated: false,
    artifact_origin_authentication: "UNVERIFIED",
    native_cryptographic_verification: "UNVERIFIED", blocker: NATIVE_BLOCKER,
    publication_authorized: false, deployment: "NOT_CHECKED", production_acceptance: "BLOCKED" };
}
